import { invoke } from "@tauri-apps/api/core";
import type {
  AppPaths,
  ApplyOutcome,
  BackupInfo,
  BaselineManifest,
  JavaEnvReport,
  EnvChange,
  EnvSnapshot,
  HostsEntry,
  OpRecord,
  Prefs,
  RemoteNodeList,
  RuntimeStatus,
  ShellCompatStatus,
  TrashItem,
  AppMemory,
  RuntimeLogFile,
  NodePkgLayout,
  NpmUserConfig,
  PrefsSaveResult,
  PnpmEnv,
  ToolCache,
} from "./types";

export const api = {
  getPaths: () => invoke<AppPaths>("get_paths"),
  setPaths: (args: AppPaths & { migrate: boolean }) =>
    invoke<AppPaths>("set_paths", {
      args: {
        config_dir: args.config_dir,
        data_dir: args.data_dir,
        log_dir: args.log_dir,
        migrate: args.migrate,
      },
    }),
  getPrefs: () => invoke<Prefs>("get_prefs"),
  setPrefs: (prefs: Prefs) => invoke<PrefsSaveResult>("set_prefs", { prefs }),
  pickDirectory: (title: string) => invoke<string | null>("pick_directory", { title }),
  isFirstRun: () => invoke<boolean>("is_first_run"),
  completeFirstRun: () => invoke<void>("complete_first_run"),
  recaptureBaseline: () => invoke<BaselineManifest>("recapture_baseline"),
  restoreOsSurface: () => invoke<string>("restore_os_surface"),
  listOps: (kind?: string, limit?: number) =>
    invoke<OpRecord[]>("list_ops", { kind: kind ?? null, limit: limit ?? 200 }),
  readTextFile: (path: string) => invoke<string>("read_text_file", { path }),
  listHosts: () =>
    invoke<[HostsEntry[], TrashItem[]]>("list_hosts"),
  getHostsContent: (id: string) => invoke<string>("get_hosts_content", { id }),
  saveHostsEntry: (payload: { id?: string | null; title: string; content: string; on: boolean }) =>
    invoke<HostsEntry>("save_hosts_entry", payload),
  setHostsOn: (id: string, on: boolean) => invoke<void>("set_hosts_on", { id, on }),
  trashHosts: (id: string) => invoke<void>("trash_hosts", { id }),
  restoreHostsTrash: (id: string) => invoke<HostsEntry>("restore_hosts_trash", { id }),
  purgeHostsTrash: (id?: string) => invoke<void>("purge_hosts_trash", { id: id ?? null }),
  readSystemHosts: () => invoke<string>("read_system_hosts"),
  applyHosts: () => invoke<ApplyOutcome>("apply_hosts"),
  envSnapshot: () => invoke<EnvSnapshot>("env_snapshot"),
  applyEnvChanges: (changes: EnvChange[]) => invoke<void>("apply_env_changes", { changes }),
  nodeStatus: () => invoke<RuntimeStatus>("node_status"),
  nodeListRemote: (force = false) => invoke<RemoteNodeList>("node_list_remote", { force }),
  nodeInstall: (version: string) => invoke<RuntimeStatus>("node_install", { version }),
  nodeUninstall: (version: string) => invoke<RuntimeStatus>("node_uninstall", { version }),
  nodeSetCurrent: (version: string) => invoke<RuntimeStatus>("node_set_current", { version }),
  nodeInfo: (version: string) => invoke<{ node: string; npm: string; ok: boolean }>("node_info", { version }),
  nodeNpmInstall: (nodeVer: string, npmVer: string) =>
    invoke<string>("node_npm_install", { nodeVer, npmVer }),
  nodePnpmInstall: (nodeVer: string) => invoke<string>("node_pnpm_install", { nodeVer }),
  nodeFixPnpm: () => invoke<PnpmEnv>("node_fix_pnpm"),
  runtimeCancel: () => invoke<void>("runtime_cancel"),
  pythonStatus: () => invoke<RuntimeStatus>("python_status"),
  pythonListRemote: (force = false) => invoke<RemoteNodeList>("python_list_remote", { force }),
  pythonInstall: (version: string) => invoke<RuntimeStatus>("python_install", { version }),
  pythonUninstall: (version: string) => invoke<RuntimeStatus>("python_uninstall", { version }),
  pythonSetCurrent: (version: string) => invoke<RuntimeStatus>("python_set_current", { version }),
  pythonFixCmd: () => invoke<RuntimeStatus>("python_fix_cmd"),
  pythonPipInstall: (pyVer: string, pipVer: string) =>
    invoke<string>("python_pip_install", { pyVer, pipVer }),
  javaStatus: () => invoke<RuntimeStatus>("java_status"),
  javaListRemote: (force = false) => invoke<RemoteNodeList>("java_list_remote", { force }),
  javaInstall: (version: string) => invoke<RuntimeStatus>("java_install", { version }),
  javaUninstall: (version: string) => invoke<RuntimeStatus>("java_uninstall", { version }),
  javaSetCurrent: (version: string) => invoke<RuntimeStatus>("java_set_current", { version }),
  javaEnvReport: () => invoke<JavaEnvReport>("java_env_report"),
  javaClaimEnv: () => invoke<JavaEnvReport>("java_claim_env"),
  golangStatus: () => invoke<RuntimeStatus>("golang_status"),
  golangListRemote: (force = false) => invoke<RemoteNodeList>("golang_list_remote", { force }),
  golangInstall: (version: string) => invoke<RuntimeStatus>("golang_install", { version }),
  golangUninstall: (version: string) => invoke<RuntimeStatus>("golang_uninstall", { version }),
  golangSetCurrent: (version: string) => invoke<RuntimeStatus>("golang_set_current", { version }),
  legacyShellStatus: () => invoke<ShellCompatStatus>("legacy_shell_status"),
  cleanupLegacyShellHooks: () => invoke<ShellCompatStatus>("cleanup_legacy_shell_hooks"),
  createBackup: (includeRuntime: boolean, destDir?: string | null) =>
    invoke<BackupInfo>("create_backup", { includeRuntime, destDir: destDir ?? null }),
  listBackups: () => invoke<BackupInfo[]>("list_backups"),
  restoreBackup: (zipPath: string) => invoke<string>("restore_backup", { zipPath }),
  baselineStatus: () => invoke<BaselineManifest | null>("baseline_status"),
  appMemory: () => invoke<AppMemory>("app_memory"),
  listRuntimeLogs: () => invoke<RuntimeLogFile[]>("list_runtime_logs"),
  nodePkgLayout: () => invoke<NodePkgLayout>("node_pkg_layout"),
  nodeNpmConfig: () => invoke<NpmUserConfig>("node_npm_config"),
  nodeSyncNpmConfig: () => invoke<NpmUserConfig>("node_sync_npm_config"),
  nodeSetRegistry: (url: string) => invoke<NpmUserConfig>("node_set_registry", { url }),
  nodeNpmCacheClean: () => invoke<string>("node_npm_cache_clean"),
  listToolCaches: () => invoke<ToolCache[]>("list_tool_caches"),
  cleanToolCache: (id: string) => invoke<string>("clean_tool_cache", { id }),
};
