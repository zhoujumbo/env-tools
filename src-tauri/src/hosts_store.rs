use crate::paths::{self, AppPaths};
use anyhow::{bail, Result};
use serde::{Deserialize, Serialize};
use std::fs;
use uuid::Uuid;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HostsEntry {
    pub id: String,
    pub title: String,
    pub on: bool,
    #[serde(default)]
    pub kind: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct HostsManifest {
    pub entries: Vec<HostsEntry>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrashItem {
    pub id: String,
    pub title: String,
    pub content: String,
    pub deleted_at: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct TrashCan {
    pub items: Vec<TrashItem>,
}

pub fn load_manifest(paths: &AppPaths) -> HostsManifest {
    let p = paths.hosts_manifest();
    fs::read_to_string(p)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default()
}

fn save_manifest(paths: &AppPaths, man: &HostsManifest) -> Result<()> {
    fs::create_dir_all(paths.hosts_dir())?;
    fs::write(paths.hosts_manifest(), serde_json::to_string_pretty(man)?)?;
    Ok(())
}

pub fn load_trash(paths: &AppPaths) -> TrashCan {
    fs::read_to_string(paths.hosts_trash())
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default()
}

fn save_trash(paths: &AppPaths, trash: &TrashCan) -> Result<()> {
    fs::write(paths.hosts_trash(), serde_json::to_string_pretty(trash)?)?;
    Ok(())
}

fn assert_entry_id(id: &str) -> Result<()> {
    Uuid::parse_str(id).map(|_| ()).map_err(|_| anyhow::anyhow!("非法 hosts id"))
}

fn entry_path(paths: &AppPaths, id: &str) -> Result<std::path::PathBuf> {
    assert_entry_id(id)?;
    if paths::has_path_escape(id) {
        bail!("非法 hosts id");
    }
    Ok(paths.hosts_entries_dir().join(format!("{id}.txt")))
}

pub fn entry_content(paths: &AppPaths, id: &str) -> String {
    let Ok(p) = entry_path(paths, id) else {
        return String::new();
    };
    fs::read_to_string(p).unwrap_or_default()
}

pub fn save_entry(
    paths: &AppPaths,
    id: Option<String>,
    title: String,
    content: String,
    on: bool,
) -> Result<HostsEntry> {
    let mut man = load_manifest(paths);
    let entry = if let Some(id) = id {
        assert_entry_id(&id)?;
        if let Some(e) = man.entries.iter_mut().find(|e| e.id == id) {
            e.title = title;
            e.on = on;
            e.clone()
        } else {
            let e = HostsEntry {
                id,
                title,
                on,
                kind: "local".into(),
            };
            man.entries.push(e.clone());
            e
        }
    } else {
        let e = HostsEntry {
            id: Uuid::new_v4().to_string(),
            title,
            on,
            kind: "local".into(),
        };
        man.entries.push(e.clone());
        e
    };
    fs::create_dir_all(paths.hosts_entries_dir())?;
    fs::write(entry_path(paths, &entry.id)?, content)?;
    save_manifest(paths, &man)?;
    Ok(entry)
}

pub fn set_on(paths: &AppPaths, id: &str, on: bool) -> Result<()> {
    assert_entry_id(id)?;
    let mut man = load_manifest(paths);
    if let Some(e) = man.entries.iter_mut().find(|e| e.id == id) {
        e.on = on;
    }
    save_manifest(paths, &man)
}

pub fn trash_entry(paths: &AppPaths, id: &str) -> Result<()> {
    assert_entry_id(id)?;
    let mut man = load_manifest(paths);
    let Some(pos) = man.entries.iter().position(|e| e.id == id) else {
        return Ok(());
    };
    let e = man.entries.remove(pos);
    let content = entry_content(paths, id);
    if let Ok(p) = entry_path(paths, id) {
        let _ = fs::remove_file(p);
    }
    save_manifest(paths, &man)?;
    let mut trash = load_trash(paths);
    trash.items.push(TrashItem {
        id: e.id,
        title: e.title,
        content,
        deleted_at: chrono::Local::now().to_rfc3339(),
    });
    save_trash(paths, &trash)
}

pub fn restore_trash(paths: &AppPaths, id: &str) -> Result<HostsEntry> {
    assert_entry_id(id)?;
    let mut trash = load_trash(paths);
    let Some(pos) = trash.items.iter().position(|i| i.id == id) else {
        anyhow::bail!("回收站中没有该条目");
    };
    let item = trash.items.remove(pos);
    save_trash(paths, &trash)?;
    save_entry(paths, Some(item.id), item.title, item.content, false)
}

pub fn purge_trash(paths: &AppPaths, id: Option<String>) -> Result<()> {
    let mut trash = load_trash(paths);
    if let Some(id) = id {
        trash.items.retain(|i| i.id != id);
    } else {
        trash.items.clear();
    }
    save_trash(paths, &trash)
}

pub fn aggregate_enabled(paths: &AppPaths) -> String {
    let man = load_manifest(paths);
    let mut out = String::from("# Generated by 环境面板 (desktop-env-tool)\r\n");
    out.push_str("# Do not edit the system hosts file directly while using this panel.\r\n\r\n");
    for e in man.entries.iter().filter(|e| e.on) {
        out.push_str(&format!("# ===== {} ({}) =====\r\n", e.title, e.id));
        let body = entry_content(paths, &e.id).replace('\r', "");
        for line in body.lines() {
            out.push_str(line);
            out.push_str("\r\n");
        }
        out.push_str("\r\n");
    }
    out
}

pub fn ensure_default_entry(paths: &AppPaths) -> Result<()> {
    let mut man = load_manifest(paths);
    let mut changed = false;
    for e in &mut man.entries {
        let t = e.title.trim();
        if t.eq_ignore_ascii_case("当前系统 hosts") || t == "当前系统 Hosts" || t == "系统 Hosts" {
            e.title = "默认方案".into();
            changed = true;
        }
    }
    if changed {
        save_manifest(paths, &man)?;
    }
    Ok(())
}
